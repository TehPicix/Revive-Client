package revivedevelopment.reviveclient.systems.modules.hunting;

import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import meteordevelopment.orbit.EventHandler;
import net.minecraft.fluid.FluidState;
import net.minecraft.network.packet.s2c.play.BlockUpdateS2CPacket;
import net.minecraft.network.packet.s2c.play.ChunkDeltaUpdateS2CPacket;
import net.minecraft.registry.RegistryKey;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.world.World;
import net.minecraft.world.chunk.ChunkSection;
import net.minecraft.world.chunk.WorldChunk;
import revivedevelopment.reviveclient.events.game.GameJoinedEvent;
import revivedevelopment.reviveclient.events.packets.PacketEvent;
import revivedevelopment.reviveclient.events.render.Render3DEvent;
import revivedevelopment.reviveclient.events.world.ChunkDataEvent;
import revivedevelopment.reviveclient.events.world.TickEvent;
import revivedevelopment.reviveclient.renderer.ShapeMode;
import revivedevelopment.reviveclient.settings.BoolSetting;
import revivedevelopment.reviveclient.settings.ColorSetting;
import revivedevelopment.reviveclient.settings.EnumSetting;
import revivedevelopment.reviveclient.settings.IntSetting;
import revivedevelopment.reviveclient.settings.Setting;
import revivedevelopment.reviveclient.settings.SettingGroup;
import revivedevelopment.reviveclient.systems.modules.Categories;
import revivedevelopment.reviveclient.systems.modules.Module;
import revivedevelopment.reviveclient.utils.render.color.Color;
import revivedevelopment.reviveclient.utils.render.color.SettingColor;

public class NewChunks extends Module {
   private final SettingGroup sgGeneral = this.settings.getDefaultGroup();
   private final SettingGroup sgRender = this.settings.createGroup("Render");
   private final Setting<Boolean> renderNew = this.sgGeneral
      .add(new BoolSetting.Builder().name("new-chunks").description("Highlight chunks that were generated while you were nearby.").defaultValue(true).build());
   private final Setting<Boolean> renderOld = this.sgGeneral
      .add(
         new BoolSetting.Builder()
            .name("old-chunks")
            .description("Highlight chunks that were proven to already exist (ticked liquid on load).")
            .defaultValue(false)
            .build()
      );
   private final Setting<Integer> renderDistance = this.sgGeneral
      .add(
         new IntSetting.Builder()
            .name("render-distance")
            .description("Maximum distance to render chunk overlays, in blocks.")
            .defaultValue(512)
            .sliderRange(32, 1024)
            .build()
      );
   private final Setting<Boolean> atPlayerLevel = this.sgRender
      .add(
         new BoolSetting.Builder().name("at-player-level").description("Renders the quads at your feet level instead of a fixed Y.").defaultValue(true).build()
      );
   private final Setting<Integer> renderY = this.sgRender
      .add(
         new IntSetting.Builder()
            .name("render-y")
            .description("Y level to render the chunk quads at.")
            .defaultValue(64)
            .sliderRange(-64, 320)
            .visible(() -> !this.atPlayerLevel.get())
            .build()
      );
   private final Setting<ShapeMode> shapeMode = this.sgRender
      .add(
         ((EnumSetting.Builder)((EnumSetting.Builder)((EnumSetting.Builder)new EnumSetting.Builder().name("shape-mode"))
                  .description("How the chunk quads are rendered."))
               .defaultValue(ShapeMode.Both))
            .build()
      );
   private final Setting<Integer> fillOpacity = this.sgRender
      .add(
         new IntSetting.Builder().name("fill-opacity").description("The opacity of the quad fill.").defaultValue(40).range(0, 255).sliderRange(0, 255).build()
      );
   private final Setting<SettingColor> newColor = this.sgRender
      .add(new ColorSetting.Builder().name("new-color").description("Color of newly generated chunks.").defaultValue(new SettingColor(255, 0, 0)).build());
   private final Setting<SettingColor> oldColor = this.sgRender
      .add(
         new ColorSetting.Builder().name("old-color").description("Color of chunks that already existed.").defaultValue(new SettingColor(0, 255, 255)).build()
      );
   private final Set<Long> newChunks = ConcurrentHashMap.newKeySet();
   private final Set<Long> oldChunks = ConcurrentHashMap.newKeySet();
   private RegistryKey<World> lastDimension;
   private int evictTimer;
   private static final int EVICT_CHUNKS = 256;
   private final Color side = new Color();
   private final Color line = new Color();

   public NewChunks() {
      super(Categories.Hunting, "new-chunks", "Highlights chunks that were just generated by the server.");
   }

   @Override
   public void onActivate() {
      this.lastDimension = this.mc.world != null ? this.mc.world.getRegistryKey() : null;
   }

   @Override
   public void onDeactivate() {
      this.newChunks.clear();
      this.oldChunks.clear();
   }

   @EventHandler
   private void onGameJoined(GameJoinedEvent event) {
      this.newChunks.clear();
      this.oldChunks.clear();
      this.lastDimension = null;
   }

   @EventHandler
   private void onTick(TickEvent.Post event) {
      if (this.mc.world != null) {
         RegistryKey<World> dimension = this.mc.world.getRegistryKey();
         if (dimension != this.lastDimension) {
            this.lastDimension = dimension;
            this.newChunks.clear();
            this.oldChunks.clear();
         }

         if (++this.evictTimer >= 100 && this.mc.player != null) {
            this.evictTimer = 0;
            int pcx = this.mc.player.getBlockX() >> 4;
            int pcz = this.mc.player.getBlockZ() >> 4;
            int keep = Math.max(256, (this.renderDistance.get() >> 4) * 2);
            this.newChunks.removeIf(k -> far(k, pcx, pcz, keep));
            this.oldChunks.removeIf(k -> far(k, pcx, pcz, keep));
         }
      }
   }

   private static boolean far(long key, int pcx, int pcz, int keep) {
      return Math.abs(ChunkPos.getPackedX(key) - pcx) > keep || Math.abs(ChunkPos.getPackedZ(key) - pcz) > keep;
   }

   @EventHandler
   private void onChunkData(ChunkDataEvent event) {
      WorldChunk chunk = event.chunk();
      long key = chunk.getPos().toLong();
      if (!this.newChunks.contains(key) && !this.oldChunks.contains(key)) {
         for (ChunkSection section : chunk.getSectionArray()) {
            if (section != null && !section.isEmpty() && section.getBlockStateContainer().hasAny(st -> {
               FluidState f = st.getFluidState();
               return !f.isEmpty() && !f.isStill();
            })) {
               for (int x = 0; x < 16; x++) {
                  for (int y = 0; y < 16; y++) {
                     for (int z = 0; z < 16; z++) {
                        FluidState fluid = section.getBlockState(x, y, z).getFluidState();
                        if (!fluid.isEmpty() && !fluid.isStill()) {
                           this.oldChunks.add(key);
                           return;
                        }
                     }
                  }
               }
            }
         }
      }
   }

   @EventHandler
   private void onPacketReceive(PacketEvent.Receive event) {
      if (event.packet instanceof ChunkDeltaUpdateS2CPacket packet) {
         packet.visitUpdates((pos, state) -> {
            FluidState fluid = state.getFluidState();
            if (!fluid.isEmpty() && !fluid.isStill()) {
               this.markNew(ChunkPos.toLong(pos));
            }
         });
      } else if (event.packet instanceof BlockUpdateS2CPacket packet) {
         FluidState fluid = packet.getState().getFluidState();
         if (!fluid.isEmpty() && !fluid.isStill()) {
            this.markNew(ChunkPos.toLong(packet.getPos()));
         }
      }
   }

   private void markNew(long key) {
      if (!this.oldChunks.contains(key)) {
         this.newChunks.add(key);
      }
   }

   @EventHandler
   private void onRender(Render3DEvent event) {
      if (this.mc.player != null) {
         double y = this.atPlayerLevel.get() ? this.mc.player.getY() : this.renderY.get().intValue();
         ShapeMode shape = this.shapeMode.get();
         if (this.renderNew.get()) {
            this.renderChunks(event, this.newChunks, this.newColor.get(), y, shape);
         }

         if (this.renderOld.get()) {
            this.renderChunks(event, this.oldChunks, this.oldColor.get(), y, shape);
         }
      }
   }

   private void renderChunks(Render3DEvent event, Set<Long> chunks, SettingColor color, double y, ShapeMode shape) {
      double rdistSq = (double)this.renderDistance.get().intValue() * this.renderDistance.get().intValue();
      double px = this.mc.player.getX();
      double pz = this.mc.player.getZ();
      this.line.set((Color)color);
      this.side.set((Color)color);
      this.side.a = shape.sides() ? this.fillOpacity.get() : 0;

      for (long key : chunks) {
         int x = ChunkPos.getPackedX(key) << 4;
         int z = ChunkPos.getPackedZ(key) << 4;
         double dx = x + 8 - px;
         double dz = z + 8 - pz;
         if (!(dx * dx + dz * dz > rdistSq)) {
            event.renderer.sideHorizontal(x, y, z, x + 16, z + 16, this.side, this.line, shape);
         }
      }
   }

   @Override
   public String getInfoString() {
      return this.newChunks.size() + "/" + this.oldChunks.size();
   }
}
